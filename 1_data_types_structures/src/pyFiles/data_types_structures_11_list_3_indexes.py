revenues = [50, 60, 55]
expenses = [10, 30, 35]

print('Simple Forward Index: revenues')
print(revenues[0])
print(revenues[1])
print(revenues[2])
print()

print('Simple Forward Index: expenses')
print(expenses[0])
print(expenses[1])
print(expenses[2])
print()


print('Backward Index: revenues')
print(revenues[-3])
print(revenues[-2])
print(revenues[-1])
print()

print('Backward Index: expenses')
print(expenses[-3])
print(expenses[-2])
print(expenses[-1])
print()
